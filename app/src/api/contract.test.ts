import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import { describe, expect, it } from 'vitest'

// O Vitest roda com `app/` como diretório de trabalho.
const root = process.cwd()

describe('OpenAPI contract', () => {
  it('the committed client matches the backend contract', async () => {
    const ast = await openapiTS(pathToFileURL(resolve(root, '../backend/openapi/openapi.yaml')))
    const header = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n'
    const committed = readFileSync(resolve(root, 'src/api/schema.d.ts'), 'utf8')
    expect(committed).toBe(header + astToString(ast))
  })
})
